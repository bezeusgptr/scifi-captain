export function getOfficer(id) {
  return OFFICERS.find((o) => o.id === id) || null;
}

export function initials(name) {
  return name
    .split(/\s+/)
    .filter(Boolean)
    .map((p) => p[0])
    .join("")
    .slice(0, 2)
    .toUpperCase();
}

function containsAny(text, words) {
  return words.some((w) => text.includes(w));
}

export function cannedReply(officer, state, userText) {
  const t = (userText || "").toLowerCase();
  const ev = state.event && state.event.status === "pending" ? state.event : null;

  if (ev) {
    if (containsAny(t, ["событ", "что происх", "что случи", "совет", "как дума", "что делать", "вариант"])) {
      const advice = (ev.advice || []).find((a) => a.officerId === officer.id);
      if (advice) {
        return `${advice.text} Это по текущему событию — «${ev.title}». Таймер уже идёт, капитан.`;
      }
      return `Сейчас на корабле «${ev.title}». Мой отдел к этому готов, но решение за вами — и лучше не дожидаться, пока его примет старпом.`;
    }
  }

  for (const [key, reply] of Object.entries(officer.keywords || {})) {
    if (t.includes(key)) return reply;
  }

  if (containsAny(t, ["привет", "здравств", "добрый", "доброе", "эй"])) {
    return officer.greeting;
  }
  if (containsAny(t, ["как дела", "как ты", "как вы", "как обстанов"])) {
    const hull = state.ship.hull;
    if (hull < 40) return "Обстановка плохая. Корпус не для парада, и люди это чувствуют. Давайте без лишней бравады.";
    if (state.ship.fuel < 30) return "Дела рабочие, но топливо уже заставляет считать каждый манёвр. Это меня нервирует.";
    return officer.chatter[0];
  }
  if (containsAny(t, ["спасибо", "благодар"])) {
    return "Есть, капитан. Обращайтесь, если ещё понажусь.";
  }
  if (containsAny(t, ["приказ", "штаб", "кеплер", "мисси"])) {
    return officer.keywords.миссия || officer.chatter[1] || officer.greeting;
  }

  const pool = officer.chatter || [officer.greeting];
  const seed = (userText || "").length + (state.log?.length || 0) + officer.id.length;
  return pool[seed % pool.length];
}
