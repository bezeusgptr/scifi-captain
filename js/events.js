export function getEvent(id) {
  return EVENTS.find((e) => e.id === id) || null;
}

export function pickOfflineEvent(state, forceId) {
  if (forceId) {
    const ev = getEvent(forceId);
    if (ev) return structuredClone(ev);
  }
  const used = new Set(state.eventHistory || []);
  let pool = EVENTS.filter((e) => !used.has(e.id));
  if (!pool.length) pool = EVENTS.slice();
  const ev = pool[Math.floor(Math.random() * pool.length)];
  return structuredClone(ev);
}
